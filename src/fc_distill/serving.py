"""fc-serve: what a model costs to serve in vLLM on this GPU (#63; #2's criterion: at least 2x
cheaper to serve than the teacher).

One run is one model at one cap on concurrent requests (vLLM's `max_num_seqs`), in a fresh engine,
with fc-eval's settings: bf16, greedy, the eval prompt, thinking off, 1,024 new tokens at most.

- **Throughput**: every test-clean prompt submitted at once, after a short warm-up.
- **Latency**: the first `--latency-rows` prompts, one request at a time.
- **Memory**: the weights vLLM loaded and the KV cache it had room for, read from its log.

`fc-serve --report` compares the saved runs: each model at its cheapest setting, in GPU-seconds per
1,000 requests, and writes results/serving.{json,md}.

Every method's model is the 0.8B with a LoRA merged in, the same size and architecture, so the raw
0.8B against the raw 2B measures the criterion.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import statistics
import sys
import time
from collections.abc import Iterator, Mapping, Sequence
from contextlib import contextmanager
from pathlib import Path
from typing import Any

from fc_distill.data import CHAT_TEMPLATE_KWARGS, load_split, to_messages
from fc_distill.tracking import git_state, hub_revision

STUDENT, TEACHER = "Qwen/Qwen3.5-0.8B", "Qwen/Qwen3.5-2B"
# fc-eval's defaults, so the served model is the evaluated one.
MAX_MODEL_LEN = 4096
MAX_TOKENS = 1024
GPU_MEM = 0.85
WARMUP_ROWS = 16
DEFAULT_JSON = Path("results/serving.json")
DEFAULT_MD = Path("results/serving.md")

_WEIGHTS = re.compile(r"Model loading took ([\d.]+) GiB")
_KV = re.compile(r"GPU KV cache size: ([\d,]+) tokens")


def read_memory(log: str) -> dict[str, Any]:
    """The weights vLLM loaded (GiB) and its KV cache capacity (tokens), from its startup log."""
    weights, kv = _WEIGHTS.search(log), _KV.search(log)
    return {
        "weights_gib": float(weights.group(1)) if weights else None,
        "kv_cache_tokens": int(kv.group(1).replace(",", "")) if kv else None,
    }


def _summary(run: Mapping[str, Any]) -> dict[str, Any]:
    latency = sorted(run["latency_seconds"])
    return {
        "max_num_seqs": run["max_num_seqs"],
        "requests_per_s": round(run["requests"] / run["seconds"], 2),
        "output_tokens_per_s": round(run["output_tokens"] / run["seconds"], 1),
        "output_tokens_per_request": round(run["output_tokens"] / run["requests"], 1),
        # One GPU, so wall-clock seconds are GPU-seconds.
        "gpu_seconds_per_1k": round(1000 * run["seconds"] / run["requests"], 2),
        "latency_p50": round(statistics.median(latency), 3),
        "latency_p90": round(latency[min(len(latency) - 1, int(0.9 * len(latency)))], 3),
        "weights_gib": run["weights_gib"],
        "kv_cache_tokens": run["kv_cache_tokens"],
    }


def report(
    runs: Sequence[Mapping[str, Any]], student: str = STUDENT, teacher: str = TEACHER
) -> dict[str, Any]:
    """Each model at every setting run, and at its cheapest one; the speed-up is the teacher's
    GPU-seconds per 1,000 requests over the student's, both at their cheapest."""
    models: dict[str, Any] = {}
    for run in sorted(runs, key=lambda r: (r["model"], r["max_num_seqs"])):
        models.setdefault(run["model"], {"settings": []})["settings"].append(_summary(run))
    for m in models.values():
        m["best"] = min(m["settings"], key=lambda s: s["gpu_seconds_per_1k"])
    speedup = None
    if student in models and teacher in models:
        speedup = round(
            models[teacher]["best"]["gpu_seconds_per_1k"]
            / models[student]["best"]["gpu_seconds_per_1k"],
            2,
        )
    return {
        "student": student,
        "teacher": teacher,
        "models": models,
        "speedup": speedup,
        "clears_2x": None if speedup is None else speedup >= 2,
    }


def render(data: Mapping[str, Any]) -> str:
    out = [
        "# Serving cost",
        "",
        "Issue #63. Generated by `uv run --no-sync fc-serve --report` from the runs in `runs/`; "
        "numbers: [`serving.json`](serving.json). vLLM on one RTX 3060 12 GB, fc-eval's settings "
        "(bf16, greedy, the eval prompt, thinking off, at most 1,024 new tokens, "
        f"`gpu_memory_utilization` {GPU_MEM}), on all test-clean prompts. Cheaper means fewer "
        "GPU-seconds per 1,000 requests, each model at its best cap on concurrent requests.",
        "",
    ]
    if data["speedup"] is not None:
        verdict = "clears" if data["clears_2x"] else "misses"
        out += [
            f"**The {data['student']} serves {data['speedup']:.1f}x cheaper than the "
            f"{data['teacher']}**, which {verdict} #2's 2x criterion.",
            "",
        ]
    out += [
        "| Model | Max concurrent | Requests/s | Output tokens/s | Tokens per request | "
        "GPU-s per 1k requests | Latency p50 / p90 (s) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for model, m in data["models"].items():
        for s in m["settings"]:
            best = s is m["best"]
            cost = (
                f"**{s['gpu_seconds_per_1k']:.1f}**" if best else f"{s['gpu_seconds_per_1k']:.1f}"
            )
            out.append(
                f"| {model} | {s['max_num_seqs']} | {s['requests_per_s']:.2f} | "
                f"{s['output_tokens_per_s']:,.0f} | {s['output_tokens_per_request']:.0f} | "
                f"{cost} | "
                f"{s['latency_p50']:.2f} / {s['latency_p90']:.2f} |"
            )
    out += [
        "",
        "Latency is one request at a time. A request's cost includes how long its answer is, "
        "and the two models' answers differ in length (tokens per request).",
        "",
        "| Model | Weights (GiB) | KV cache (tokens) |",
        "|---|---:|---:|",
    ]
    for model, m in data["models"].items():
        b = m["best"]
        weights = "-" if b["weights_gib"] is None else f"{b['weights_gib']:.2f}"
        kv = "-" if b["kv_cache_tokens"] is None else f"{b['kv_cache_tokens']:,}"
        out.append(f"| {model} | {weights} | {kv} |")
    return "\n".join(out) + "\n"


@contextmanager
def _output_to(path: Path) -> Iterator[None]:
    """Send this process's stdout and stderr, and its children's (vLLM's engine core, which logs
    to stdout), to a file."""
    sys.stdout.flush()
    sys.stderr.flush()
    saved = [os.dup(1), os.dup(2)]
    with path.open("w") as f:
        os.dup2(f.fileno(), 1)
        os.dup2(f.fileno(), 2)
        try:
            yield
        finally:
            sys.stdout.flush()
            sys.stderr.flush()
            for fd, copy in zip((1, 2), saved, strict=True):
                os.dup2(copy, fd)
                os.close(copy)


def measure(model: str, max_num_seqs: int, n: int | None, latency_rows: int, out: Path) -> None:
    # As in fc-eval: greedy decoding doesn't need FlashInfer's JIT sampler.
    os.environ.setdefault("VLLM_USE_FLASHINFER_SAMPLER", "0")
    import vllm
    from vllm import LLM, SamplingParams

    prompts = [to_messages(r) for r in load_split("test-clean")][:n]
    params = SamplingParams(temperature=0.0, max_tokens=MAX_TOKENS)
    log = out / "vllm.log"
    with _output_to(log):
        llm = LLM(
            model=model,
            max_model_len=MAX_MODEL_LEN,
            gpu_memory_utilization=GPU_MEM,
            max_num_seqs=max_num_seqs,
            limit_mm_per_prompt={"image": 0, "video": 0},
        )

        def chat(batch: Sequence[Any]) -> Any:
            return llm.chat(
                list(batch), params, chat_template_kwargs=CHAT_TEMPLATE_KWARGS, use_tqdm=False
            )

        chat(prompts[:WARMUP_ROWS])
        start = time.perf_counter()
        outputs = chat(prompts)
        seconds = time.perf_counter() - start
        latency = []
        for prompt in prompts[:latency_rows]:
            t = time.perf_counter()
            chat([prompt])
            latency.append(round(time.perf_counter() - t, 4))
    run = {
        "model": model,
        "model_revision": hub_revision(model),
        "max_num_seqs": max_num_seqs,
        "requests": len(prompts),
        "seconds": round(seconds, 2),
        "input_tokens": sum(len(o.prompt_token_ids) for o in outputs),
        "output_tokens": sum(len(o.outputs[0].token_ids) for o in outputs),
        "latency_seconds": latency,
        **read_memory(log.read_text()),
        "vllm": vllm.__version__,
        "git": git_state(),
    }
    (out / "summary.json").write_text(json.dumps(run, indent=2) + "\n")
    print(json.dumps({k: v for k, v in run.items() if k != "latency_seconds"}, indent=2))


def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--model", help="a Hub id, e.g. Qwen/Qwen3.5-0.8B")
    ap.add_argument("--max-num-seqs", type=int, default=256, help="cap on concurrent requests")
    ap.add_argument("--n", type=int, default=None, help="first n test-clean prompts (default: all)")
    ap.add_argument("--latency-rows", type=int, default=50)
    ap.add_argument("--out", type=Path, default=None, help="default: runs/serve-<model>-s<cap>")
    ap.add_argument(
        "--report", action="store_true", help="write results/serving.{json,md} from runs/serve-*"
    )
    ap.add_argument(
        "--allow-dirty", action="store_true", help="run even with uncommitted changes (recorded)"
    )
    args = ap.parse_args()
    if (args.model is None) == (not args.report):
        ap.error("give exactly one of --model or --report")
    if args.model and not args.allow_dirty and git_state()["dirty"]:
        ap.error("uncommitted changes to tracked files; commit them or pass --allow-dirty")
    return args


def main() -> None:
    args = parse_args()
    if args.report:
        runs = [
            json.loads(p.read_text()) for p in sorted(Path("runs").glob("serve-*/summary.json"))
        ]
        data = report(runs)
        DEFAULT_JSON.write_text(json.dumps(data, indent=2) + "\n")
        DEFAULT_MD.write_text(render(data))
        print(f"wrote {DEFAULT_JSON} and {DEFAULT_MD}")
        return
    out: Path = (
        args.out or Path("runs") / f"serve-{args.model.replace('/', '_')}-s{args.max_num_seqs}"
    )
    out.mkdir(parents=True, exist_ok=True)
    measure(args.model, args.max_num_seqs, args.n, args.latency_rows, out)


if __name__ == "__main__":
    main()
